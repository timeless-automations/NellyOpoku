// Set default language to NL (Belgian market)
let currentLang = 'nl';

function getInitialLanguage() {
  const langParam = new URLSearchParams(window.location.search).get('lang');
  if (langParam && translations[langParam]) {
    return langParam;
  }
  try {
    const saved = localStorage.getItem('language');
    if (saved && translations[saved]) return saved;
  } catch (_) {}
  return 'nl';
}

function applyLangToPageLinks(lang) {
  const pageNames = ['index.html', 'vastgoed.html', 'verzekeringen.html', 'autodealers.html'];
  document.querySelectorAll('a[href]').forEach((anchor) => {
    const href = anchor.getAttribute('href');
    if (!href || href.startsWith('mailto:') || href.startsWith('http') || href.startsWith('#')) return;
    let url;
    try {
      url = new URL(href, window.location.href);
    } catch (_) {
      return;
    }
    const file = url.pathname.split('/').pop() || 'index.html';
    if (!pageNames.includes(file)) return;
    url.searchParams.set('lang', lang);
    const pathOnly = href.split('#')[0].split('?')[0];
    const slash = pathOnly.lastIndexOf('/');
    const dir = slash >= 0 ? pathOnly.slice(0, slash + 1) : '';
    anchor.setAttribute('href', dir + file + url.search + url.hash);
  });
}

function setLanguage(lang) {
  if (!translations[lang]) {
    console.error(`Language ${lang} not found`);
    return;
  }
  
  currentLang = lang;
  try { localStorage.setItem('language', lang); } catch (_) {}
  document.documentElement.lang = lang;
  applyLangToPageLinks(lang);
  
  // Update all i18n elements
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (translations[lang][key]) {
      element.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll('[data-i18n-content]').forEach(element => {
    const key = element.getAttribute('data-i18n-content');
    if (translations[lang][key]) {
      element.setAttribute('content', translations[lang][key]);
    }
  });

  const nextField = document.getElementById('form-next');
  if (nextField) {
    const thanks = 'https://timelessautomations.be/bedankt/';
    nextField.value = lang === 'nl' ? thanks : thanks + '?lang=' + encodeURIComponent(lang);
  }
  
  // Update language buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === lang) {
      btn.classList.add('active');
      btn.setAttribute('aria-pressed', 'true');
    } else {
      btn.classList.remove('active');
      btn.setAttribute('aria-pressed', 'false');
    }
  });
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', () => {
  setLanguage(getInitialLanguage());
  
  // Add click handlers to language buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const lang = btn.getAttribute('data-lang');
      setLanguage(lang);
    });
  });
});
